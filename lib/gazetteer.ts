export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

export function findNearestLocation(lat: number, lng: number): { location: GeoLocation; distanceKm: number } {
  let nearest = UKRAINIAN_GAZETTEER[0];
  let minDistance = Infinity;

  for (const loc of UKRAINIAN_GAZETTEER) {
    const dist = calculateDistanceKm(lat, lng, loc.lat, loc.lng);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = loc;
    }
  }

  return { location: nearest, distanceKm: minDistance };
}

function escapeRegex(string: string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export interface ExtractedGeoResult {
  locations: GeoLocation[];
  regionalZones: RegionalZone[];
  isSpecificLocationFound: boolean;
  matchedKeywords: string[];
}

export function extractLocationsFromText(text: string): GeoLocation[] {
  const res = extractGeoFromText(text);
  return res.locations;
}

export function extractGeoFromText(text: string): ExtractedGeoResult {
  // Normalize text: replace punctuation separators (slashes, hyphens, brackets) with space for scanning,
  // but keep words and standard letters
  const normalized = text.toLowerCase()
    .replace(/[«»"'\(\)\[\]]/g, ' ')
    .replace(/[\/\\]/g, ' ')
    .replace(/[,:;]/g, ' ');

  const matchedLocations: GeoLocation[] = [];
  const matchedZones: RegionalZone[] = [];
  const matchedKeywords: string[] = [];
  const seenNames = new Set<string>();

  // Build sorted list of alias matchers (longest aliases first)
  const sortedGazetteer = [...UKRAINIAN_GAZETTEER].sort((a, b) => {
    const maxA = Math.max(...a.aliases.map(al => al.length));
    const maxB = Math.max(...b.aliases.map(al => al.length));
    return maxB - maxA;
  });

  // 1. Match Specific Locations (Towns, Microdistricts, Cities) with STRICT Unicode word boundaries
  for (const loc of sortedGazetteer) {
    let hasMatch = false;

    // Sort this location's aliases by length descending
    const sortedAliases = [...loc.aliases].sort((a, b) => b.length - a.length);

    for (const alias of sortedAliases) {
      const aliasNorm = alias.toLowerCase().trim();
      if (aliasNorm.length < 2) continue;
      const escaped = escapeRegex(aliasNorm);
      // Strictly require word boundary at start and end
      const regex = new RegExp(`(?:^|[^\\p{L}\\p{N}])${escaped}(?:[^\\p{L}\\p{N}]|$)`, 'iu');
      if (regex.test(normalized) || regex.test(text.toLowerCase())) {
        hasMatch = true;
        matchedKeywords.push(aliasNorm);
        break;
      }
    }

    if (hasMatch && !seenNames.has(loc.name)) {
      matchedLocations.push(loc);
      seenNames.add(loc.name);
    }
  }

  // 2. Match Regional Zones (e.g. "Київщина", "Чернігівщина", "Харківщина")
  for (const zone of REGIONAL_ZONES) {
    const sortedZoneAliases = [...zone.aliases].sort((a, b) => b.length - a.length);
    for (const alias of sortedZoneAliases) {
      const aliasNorm = alias.toLowerCase().trim();
      const escaped = escapeRegex(aliasNorm);
      const regex = new RegExp(`(?:^|[^\\p{L}\\p{N}])${escaped}(?:[^\\p{L}\\p{N}]|$)`, 'iu');
      if (regex.test(normalized) || regex.test(text.toLowerCase())) {
        if (!matchedZones.some(z => z.name === zone.name)) {
          matchedZones.push(zone);
          matchedKeywords.push(aliasNorm);
        }
        break;
      }
    }
  }

  return {
    locations: matchedLocations,
    regionalZones: matchedZones,
    isSpecificLocationFound: matchedLocations.length > 0,
    matchedKeywords
  };
}

export function calculateBearingDegrees(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const dLon = ((lng2 - lng1) * Math.PI) / 180;
  const lat1Rad = (lat1 * Math.PI) / 180;
  const lat2Rad = (lat2 * Math.PI) / 180;

  const y = Math.sin(dLon) * Math.cos(lat2Rad);
  const x =
    Math.cos(lat1Rad) * Math.sin(lat2Rad) -
    Math.sin(lat1Rad) * Math.cos(lat2Rad) * Math.cos(dLon);

  const brng = (Math.atan2(y, x) * 180) / Math.PI;
  return Math.round((brng + 360) % 360);
}

export function getBearingSectorUk(bearingDeg: number): string {
  if (bearingDeg >= 337.5 || bearingDeg < 22.5) return 'Північ (N)';
  if (bearingDeg >= 22.5 && bearingDeg < 67.5) return 'Північний Схід (NE)';
  if (bearingDeg >= 67.5 && bearingDeg < 112.5) return 'Схід (E)';
  if (bearingDeg >= 112.5 && bearingDeg < 157.5) return 'Південний Схід (SE)';
  if (bearingDeg >= 157.5 && borderDegCheck(bearingDeg)) return 'Південь (S)';
  if (bearingDeg >= 202.5 && bearingDeg < 247.5) return 'Південний Захід (SW)';
  if (bearingDeg >= 247.5 && bearingDeg < 292.5) return 'Захід (W)';
  return 'Північний Захід (NW)';
}

function borderDegCheck(deg: number): boolean {
  return deg < 202.5;
}
